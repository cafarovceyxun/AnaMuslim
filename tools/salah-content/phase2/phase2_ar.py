"""Mərhələ 2: hər çıxarışın ərəbcə qarşılığı hədisin saxlanmış `text_ar`-ından kəsilir (Mərhələ 1-in `cut`-u).

Lövbərlər hərəkəsiz yazılır; axtarış hərəkə, tətvil, həmzə daşıyıcısı və təqdimat formalarını qatlayır, amma
qaytarılan dilim **xam** mətndir — qaynaq vərəqindəki vurğu tam düşsün. (start, end) — end yoxdursa yalnız start.
"""
import re, unicodedata

HARAKA = re.compile('[ً-ْٰـ­]')


def fold(ch):
    c = unicodedata.normalize('NFKC', ch)
    c = HARAKA.sub('', c)
    c = re.sub('[أإآٱ]', 'ا', c).replace('ى', 'ي').replace('ة', 'ه')
    c = re.sub(r'\s+', ' ', c)
    return c


def folded_with_map(raw):
    out, idx = [], []
    for i, ch in enumerate(raw):
        for c in fold(ch):
            if c == ' ' and out and out[-1] == ' ':
                continue
            out.append(c)
            idx.append(i)
    return ''.join(out), idx


def cut(raw, start, end=None):
    f, idx = folded_with_map(raw)
    fs = ''.join(fold(c) for c in start)
    i = f.find(fs)
    if i < 0:
        raise KeyError(f'start not found: {start}')
    fe = ''.join(fold(c) for c in (end or start))
    j = f.find(fe, i) if end else i
    if j < 0:
        raise KeyError(f'end not found: {end}')
    a, b = idx[i], idx[j + len(fe) - 1] + 1
    while b < len(raw) and HARAKA.match(raw[b]):
        b += 1
    return raw[a:b].strip()



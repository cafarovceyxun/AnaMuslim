    private class Row(
        val year: Double,
        val altitudeKm: Double,
        val latitude: Double,
        val longitude: Double,
        val declination: Double,
        val inclination: Double,
        val total: Double,
    )

    @Test
    fun matchesTheOfficialNoaaTestValues() {
        var worstDeclination = 0.0
        var worstInclination = 0.0
        var worstTotal = 0.0

        for (row in NOAA_TEST_VALUES) {
            val field = GeomagneticModel.fieldAt(
                latitudeDeg = row.latitude,
                longitudeDeg = row.longitude,
                altitudeKm = row.altitudeKm,
                decimalYear = row.year,
            )

            // Deklinasiya cədvəldə iki onluq rəqəmlə verilib, ona görə hədd yuvarlaqlaşdırmadır.
            val dDelta = abs(QiblaMath.signedDeltaDegrees(row.declination, field.declinationDeg))
            val iDelta = abs(field.inclinationDeg - row.inclination)
            val fDelta = abs(field.totalNanoTesla - row.total)

            if (dDelta > worstDeclination) worstDeclination = dDelta
            if (iDelta > worstInclination) worstInclination = iDelta
            if (fDelta > worstTotal) worstTotal = fDelta

            assertTrue(
                dDelta < 0.01,
                "D: ${row.latitude}, ${row.longitude}, ${row.altitudeKm} km, ${row.year} → " +
                    "${field.declinationDeg}, gözlənilən ${row.declination}",
            )
            assertTrue(
                iDelta < 0.01,
                "I: ${row.latitude}, ${row.longitude} → ${field.inclinationDeg}, " +
                    "gözlənilən ${row.inclination}",
            )
            assertTrue(
                fDelta < 0.5,
                "F: ${row.latitude}, ${row.longitude} → ${field.totalNanoTesla}, " +
                    "gözlənilən ${row.total}",
            )
        }

        println("WMM2025 ən pis sapma — D: $worstDeclination°, I: $worstInclination°, F: $worstTotal nT")
    }

    @Test
    fun decimalYearTracksTheCalendar() {
        // 2025-01-01T00:00:00Z = 1735689600000 ms.
        val year = GeomagneticModel.decimalYear(1_735_689_600_000L)

        assertTrue(abs(year - 2025.0) < 0.01, "alındı $year")
    }

    @Test
    fun modelExpiryIsReported() {
        // 2027-01-01 — model içindədir.
        assertFalse(GeomagneticModel.isExpired(1_798_761_600_000L))
        // 2031-01-01 — model keçib.
        assertTrue(GeomagneticModel.isExpired(1_925_078_400_000L))
    }

    @Test
    fun epochAndExpiryAreFiveYearsApart() {
        assertEquals(5.0, GeomagneticModel.EXPIRY_YEAR - GeomagneticModel.EPOCH_YEAR)
    }


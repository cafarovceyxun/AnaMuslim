/**
 * WMM2025 modeli — **NOAA-nın rəsmi test cədvəli ilə**.
 *
 * Aşağıdakı 100 sətir `WMM2025COF.zip` arxivindəki `WMM2025_TestValues.txt` faylındandır və
 * **generasiya olunub**, əl ilə yazılmayıb. Bu, modelin düzgün portlandığının yeganə etibarlı
 * sübutudur: sferik harmonik açılışda bir işarə və ya bir normallaşdırma əmsalı səhv olsa nəticə
 * hələ də "ağlabatan" görünür (onluqlarla dərəcə sürüşür, NaN çıxmır), ona görə gözlə yoxlamaq
 * mümkün deyil.
 *
 * Cədvəl həm müxtəlif hündürlükləri (3–94 km), həm iki tarixi (2025.0 və 2025.5 — yəni sekulyar
 * dəyişmə həddini), həm də qütbə yaxın enlikləri əhatə edir.
 */
